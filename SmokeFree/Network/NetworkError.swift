import Foundation

/// Розрізняє три різновиди відмов запиту, як того вимагає завдання:
/// транспортна помилка, невдалий HTTP-статус, помилка декодування —
/// плюс окремий випадок порожньої відповіді (сервер відповів 200, але без даних).
enum NetworkError: Error, Equatable, LocalizedError {
    /// Запит не дійшов до сервера чи назад: немає мережі, обірване з'єднання, таймаут.
    case transport(String)
    /// Сервер відповів, але статус поза діапазоном 200...299.
    case badStatus(code: Int)
    /// Тіло відповіді не вдалося розібрати як очікувану модель.
    case decoding(String)
    /// Відповідь коректна, але не містить жодної цитати.
    case empty

    var errorDescription: String? {
        switch self {
        case .transport:
            return "Немає з'єднання з інтернетом. Перевірте мережу й спробуйте ще раз."
        case .badStatus(let code):
            return "Сервер повернув помилку (\(code)). Спробуйте пізніше."
        case .decoding:
            return "Не вдалося розпізнати відповідь сервера."
        case .empty:
            return "Сервер поки не має жодної цитати для показу."
        }
    }
}
